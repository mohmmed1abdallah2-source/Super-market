/// Domain commands and repository boundaries for party ledger operations.

/// Valid party categories accepted by the ledger domain.
enum LedgerPartyType { customer, supplier, employee, partner, representative }

/// Receipt and payment types supported by the voucher posting use case.
enum LedgerVoucherType { receipt, payment }

/// A validated command to create a party in one branch.
class CreatePartyCommand {
  /// Creates a party command.
  const CreatePartyCommand({
    required this.branchId,
    required this.partyType,
    required this.code,
    required this.name,
    required this.creditLimit,
    required this.paymentTermsDays,
    required this.priceTier,
    this.phone,
    this.address,
  });

  /// Authenticated branch UUID.
  final String branchId;

  /// Party category.
  final LedgerPartyType partyType;

  /// Branch-unique party code.
  final String code;

  /// Display name.
  final String name;

  /// Optional phone number.
  final String? phone;

  /// Optional postal address.
  final String? address;

  /// Maximum outstanding amount allowed.
  final double creditLimit;

  /// Agreed payment terms in days.
  final int paymentTermsDays;

  /// RETAIL or WHOLESALE.
  final String priceTier;
}

/// A command to post a receipt or payment voucher.
class PostVoucherCommand {
  /// Creates a voucher command.
  const PostVoucherCommand({
    required this.branchId,
    required this.operationId,
    required this.voucherType,
    required this.partyId,
    required this.cashAccountId,
    required this.amount,
    required this.method,
    required this.idempotencyKey,
    required this.requestHash,
    this.walletRefNo,
    this.description = '',
  });

  /// Authenticated branch UUID.
  final String branchId;

  /// Stable UUID generated by the originating device.
  final String operationId;

  /// RECEIPT or PAYMENT.
  final LedgerVoucherType voucherType;

  /// Related party UUID.
  final String partyId;

  /// Cash drawer or wallet UUID.
  final String cashAccountId;

  /// Positive voucher amount.
  final double amount;

  /// CASH or WALLET.
  final String method;

  /// Stable HTTP idempotency key reused for retries.
  final String idempotencyKey;

  /// SHA-256 hash of the canonical request.
  final String requestHash;

  /// Wallet transfer notification reference.
  final String? walletRefNo;

  /// Optional voucher explanation.
  final String description;
}

/// Repository boundary for party, statement and voucher operations.
abstract interface class LedgerRepository {
  /// Creates a party with a stable idempotency key.
  Future<Map<String, Object?>> createParty(
    CreatePartyCommand command, {
    required String idempotencyKey,
    required String requestHash,
  });

  /// Lists parties and their ledger-derived balances.
  Future<List<Map<String, Object?>>> listParties({
    required String branchId,
    String? partyType,
    int limit,
    String? cursor,
  });

  /// Reads a party statement and its calculated closing balance.
  Future<Map<String, Object?>> getPartyStatement({
    required String branchId,
    required String partyId,
    DateTime? from,
    DateTime? to,
    int limit,
    String? cursor,
  });

  /// Posts a receipt or payment and all associated financial effects atomically.
  Future<Map<String, Object?>> postVoucher(PostVoucherCommand command);

  /// Lists vouchers for a branch.
  Future<List<Map<String, Object?>>> listVouchers({
    required String branchId,
    String? partyId,
    String? voucherType,
    DateTime? from,
    DateTime? to,
  });

  /// Lists cash drawers and wallets for a branch.
  Future<List<Map<String, Object?>>> listCashAccounts({
    required String branchId,
  });
}
